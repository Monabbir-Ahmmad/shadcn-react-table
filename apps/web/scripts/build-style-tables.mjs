// Copies the data-table module once per shadcn style, pointing its primitive
// imports at that style's kit, so each style page renders the real table in
// that style. Offline and fast; runs before dev, build and typecheck.
import {
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const WEB = join(dirname(fileURLToPath(import.meta.url)), "..")
const TABLE = join(
  WEB,
  "../../packages/shadcn-react-table/src/components/data-table"
)
const OUT = join(WEB, "generated/style-tables")
const TEMPLATE = readFileSync(
  join(WEB, "scripts/style-frame-template.tsx"),
  "utf8"
)
const styles = JSON.parse(
  readFileSync(join(WEB, "style-kits/styles.json"), "utf8")
)

const HEADER =
  "// @ts-nocheck\n/* eslint-disable */\n// GENERATED by apps/web/scripts/build-style-tables.mjs — do not edit.\n"

function copy(dir, dest, style) {
  mkdirSync(dest, { recursive: true })
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const from = join(dir, entry.name)
    const to = join(dest, entry.name)
    if (entry.isDirectory()) {
      if (entry.name === "locales") continue
      copy(from, to, style)
    } else if (/\.tsx?$/.test(entry.name) && !/\.test\./.test(entry.name)) {
      const src = readFileSync(from, "utf8")
        .replaceAll("\r\n", "\n")
        .replaceAll("@workspace/ui/components/", `@/style-kits/${style}/`)
      writeFileSync(to, HEADER + src)
    }
  }
}

rmSync(OUT, { recursive: true, force: true })
for (const { name } of styles) {
  const dir = join(OUT, name)
  copy(TABLE, join(dir, "data-table"), name)
  writeFileSync(
    join(dir, "frame-table.tsx"),
    TEMPLATE.replaceAll("__STYLE__", name)
  )
}
console.log(`style tables: ${styles.map((s) => s.name).join(", ")}`)
